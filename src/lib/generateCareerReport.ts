import jsPDF from "jspdf"
import autoTable from "jspdf-autotable"

type ReportData = {
  fullName: string
  role: string
  experience: string
  score: number
  summary?: string
  topRisk?: string
  topOpportunity?: string
  harshTruth?: string
  encouragement?: string
  strengths?: string[]
  gaps?: {
    skill: string
    priority: string
    time_to_learn: string
  }[]
  careerGoal?: string
}

export function generateCareerReport(data: ReportData) {
  const doc = new jsPDF()
  const pageWidth = doc.internal.pageSize.getWidth()

  // Header
  doc.setFillColor(15, 23, 42) // slate-900
  doc.rect(0, 0, pageWidth, 40, "F")

  doc.setTextColor(255, 255, 255)
  doc.setFontSize(22)
  doc.setFont("helvetica", "bold")
  doc.text("FutureProof", 20, 25)

  doc.setFontSize(11)
  doc.setFont("helvetica", "normal")
  doc.text("Career Progress Report", 20, 33)

  // User Info
  doc.setTextColor(15, 23, 42)
  doc.setFontSize(14)
  doc.setFont("helvetica", "bold")
  doc.text(data.fullName || "Career Report", 20, 55)

  doc.setFontSize(10)
  doc.setFont("helvetica", "normal")
  doc.setTextColor(100, 116, 139)
  doc.text(`${data.role || "Professional"}  •  ${data.experience || "0"} years experience`, 20, 62)

  // Score Box
  doc.setFillColor(241, 245, 249)
  doc.roundedRect(20, 72, 50, 30, 4, 4, "F")

  doc.setTextColor(15, 23, 42)
  doc.setFontSize(24)
  doc.setFont("helvetica", "bold")
  doc.text(String(data.score || "—"), 35, 92)

  doc.setFontSize(9)
  doc.setFont("helvetica", "normal")
  doc.setTextColor(100, 116, 139)
  doc.text("Career Score", 28, 98)

  // Summary
  let y = 115
  if (data.summary) {
    doc.setTextColor(15, 23, 42)
    doc.setFontSize(11)
    doc.setFont("helvetica", "bold")
    doc.text("Summary", 20, y)

    doc.setFont("helvetica", "normal")
    doc.setFontSize(10)
    doc.setTextColor(51, 65, 85)
    const summaryLines = doc.splitTextToSize(data.summary, pageWidth - 40)
    doc.text(summaryLines, 20, y + 8)
    y += 8 + summaryLines.length * 5 + 10
  }

  // Risk & Opportunity
  if (data.topRisk || data.topOpportunity) {
    doc.setFontSize(11)
    doc.setFont("helvetica", "bold")
    doc.setTextColor(15, 23, 42)
    doc.text("Key Insights", 20, y)
    y += 8

    if (data.topRisk) {
      doc.setFontSize(9)
      doc.setFont("helvetica", "bold")
      doc.setTextColor(185, 28, 28)
      doc.text("TOP RISK", 20, y)
      doc.setFont("helvetica", "normal")
      doc.setTextColor(51, 65, 85)
      const riskLines = doc.splitTextToSize(data.topRisk, pageWidth - 40)
      doc.text(riskLines, 20, y + 6)
      y += 6 + riskLines.length * 5 + 8
    }

    if (data.topOpportunity) {
      doc.setFontSize(9)
      doc.setFont("helvetica", "bold")
      doc.setTextColor(21, 128, 61)
      doc.text("TOP OPPORTUNITY", 20, y)
      doc.setFont("helvetica", "normal")
      doc.setTextColor(51, 65, 85)
      const oppLines = doc.splitTextToSize(data.topOpportunity, pageWidth - 40)
      doc.text(oppLines, 20, y + 6)
      y += 6 + oppLines.length * 5 + 10
    }
  }

  // Skill Gaps Table
  if (data.gaps && data.gaps.length > 0) {
    doc.setFontSize(11)
    doc.setFont("helvetica", "bold")
    doc.setTextColor(15, 23, 42)
    doc.text("Critical Skill Gaps", 20, y)
    y += 4

    autoTable(doc, {
      startY: y,
      head: [["Skill", "Priority", "Time to Learn"]],
      body: data.gaps.map((g) => [g.skill, g.priority, g.time_to_learn]),
      theme: "striped",
      headStyles: {
        fillColor: [15, 23, 42],
        textColor: [255, 255, 255],
        fontSize: 9,
      },
      bodyStyles: {
        fontSize: 9,
        textColor: [51, 65, 85],
      },
      margin: { left: 20, right: 20 },
    })

    y = (doc as any).lastAutoTable.finalY + 12
  }

  // Goal
  if (data.careerGoal) {
    doc.setFontSize(11)
    doc.setFont("helvetica", "bold")
    doc.setTextColor(15, 23, 42)
    doc.text("Career Goal", 20, y)

    doc.setFont("helvetica", "normal")
    doc.setFontSize(10)
    doc.setTextColor(51, 65, 85)
    doc.text(data.careerGoal, 20, y + 8)
    y += 20
  }

  // Footer
  doc.setFontSize(8)
  doc.setTextColor(148, 163, 184)
  doc.text(
    `Generated by FutureProof on ${new Date().toLocaleDateString()}`,
    20,
    doc.internal.pageSize.getHeight() - 15
  )

  // Save
  doc.save(`FutureProof-Career-Report-${data.fullName || "User"}.pdf`)
}